"""Generate each binding's conformance report from the checks (Authoring Standard §8.1).

    python tooling/bindings/conformance.py [--check] [--output DIR] [--platform NAME ...]

Runs the binding tests (`tooling/bindings/tests`) and the package tests
(`tooling/validation/tests/test_binding_package.py`) once, recording every outcome against
the binding it is evidence for. It then renders both reference specifications under every
example organisation profile for each platform and collects the gaps their manifests
report. With the gaps the binding declares (its `PLATFORM_PROFILE.md` `Gaps`), that is the
report: what passes, what fails, what was skipped, and each gap. A binding is `standard`
only when its report shows none of the last three.

Each report is written to `implementation/{platform}/CONFORMANCE.md`, or under `--output`.
With `--check` nothing is written in place: the run fails if a committed report differs from
the regenerated one, naming any gap the committed report does not carry, since a change must
never add a gap unseen (§8.1). Engine-version lines are compared loosely, as they depend on
where the tests ran. The exit code is also 1 when any test failed, errored or was skipped:
a skipped engine is a gap, never a pass.

The engine tests need their drivers and connections (see tooling/bindings/README.md); a
report generated without them says so.
"""
import argparse
import json
import re
import sys
import unittest
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tooling" / "bindings"))
sys.path.insert(0, str(REPO / "tooling" / "build"))

import build_context  # noqa: E402
from binding import load_binding  # noqa: E402
from design_lint import parse_frontmatter  # noqa: E402
from render import render_context  # noqa: E402

EXAMPLE = REPO / "examples" / "it-service-desk-data-product"
SPECIFICATIONS = (EXAMPLE / "design-output" / "design_specification.md",
                  REPO / "tooling" / "evals" / "reference" / "customer-orders.md")
SUITES = ((REPO / "tooling" / "bindings" / "tests", "test*.py"),
          (REPO / "tooling" / "validation" / "tests", "test_binding_package.py"))
GROUPS = {"Rendering": "Rendering and portability", "TeradataDialect": "Dialect",
          "BindingPackage": "Package"}
RANK = {"pass": 0, "skip": 1, "fail": 2, "error": 3}
MARKER = "<!-- Generated by tooling/bindings/conformance.py. Do not edit: regenerate it. -->"
ENGINE_LINE = "Engine evidence:"


def platforms():
    return [p.name for p in sorted((REPO / "implementation").iterdir())
            if (p / "PLATFORM_PROFILE.md").exists() and load_binding(p.name)[0].phases]


class Recorder(unittest.TextTestResult):
    """Every outcome, against the binding it evidences: the test class's `platform`, or a
    subtest's `platform` parameter; a test with neither is shared tooling evidence."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.outcomes = defaultdict(dict)   # (class, method) -> {platform or None: (status, detail)}
        self.labels, self.versions = {}, {}

    def _key(self, test):
        self.labels.setdefault((type(test).__name__, test._testMethodName), _label(test))
        return type(test).__name__, test._testMethodName

    def _record(self, test, platform, status, detail=None):
        slot = self.outcomes[self._key(test)]
        if platform not in slot or RANK[status] > RANK[slot[platform][0]]:
            slot[platform] = (status, detail)

    @staticmethod
    def _detail(err):
        """The first line of the failure, made the same wherever the tests ran: paths relative
        to the repository, unordered collections and match objects elided."""
        lines = [line for line in str(err[1]).strip().splitlines() if line.strip()]
        text = lines[0] if lines else err[0].__name__
        for root in {str(REPO), str(REPO).replace("\\", "/")}:
            text = text.replace(root + "\\", "").replace(root + "/", "")
        text = re.sub(r"(?<=[\w.-])\\(?=[\w.-])", "/", text)  # Windows path separators
        text = re.sub(r"\{[^{}]*\}", "{...}", text)
        text = re.sub(r"<re\.Match object; span=\(\d+, \d+\), match=([^>]*)>", r"\1", text)
        return text[:300]

    def addSuccess(self, test):
        super().addSuccess(test)
        if getattr(test, "engine_version", None):
            self.versions[test.platform] = test.engine_version
        self._record(test, getattr(type(test), "platform", None), "pass")

    def addFailure(self, test, err):
        super().addFailure(test, err)
        self._record(test, getattr(type(test), "platform", None), "fail", self._detail(err))

    def addError(self, test, err):
        super().addError(test, err)
        if isinstance(test, unittest.TestCase):
            self._record(test, getattr(type(test), "platform", None), "error", self._detail(err))
        else:  # a class or module that failed to set up: every binding's report shows it
            key = ("<setup>", str(test))
            self.labels[key] = f"Set-up of {test}"
            self.outcomes[key][None] = ("error", self._detail(err))

    def addSkip(self, test, reason):
        super().addSkip(test, reason)
        self._record(test, getattr(type(test), "platform", None), "skip", reason)

    def addSubTest(self, test, subtest, err):
        super().addSubTest(test, subtest, err)
        platform = subtest.params.get("platform", getattr(type(test), "platform", None))
        if err is None:
            self._record(test, platform, "pass")
        else:
            status = "fail" if issubclass(err[0], test.failureException) else "error"
            self._record(test, platform, status, self._detail(err))


ABBREVIATIONS = {"itsd": "ITSD", "cli": "CLI"}


def _label(test):
    """The test's name as a sentence: names are written to be read."""
    words = [ABBREVIATIONS.get(w, w) for w in test._testMethodName[len("test_"):].split("_")]
    text = " ".join(words)
    return text[:1].upper() + text[1:]


def run_tests(stream):
    suite = unittest.TestSuite()
    for directory, pattern in SUITES:
        suite.addTests(unittest.defaultTestLoader.discover(str(directory), pattern=pattern,
                                                           top_level_dir=str(directory)))
    runner = unittest.TextTestRunner(stream=stream, verbosity=2, resultclass=Recorder)
    return runner.run(suite)


def build_gaps(platform):
    """Each gap the reference builds report on this platform, with the builds reporting it."""
    gaps = defaultdict(list)
    profiles = [p for p in sorted((EXAMPLE / "profiles").glob("*.md"))
                if (parse_frontmatter(p.read_text(encoding="utf-8"))[0] or {}).get("platform") == platform]
    for spec in SPECIFICATIONS:
        for profile in profiles:
            ctx, findings = build_context.resolve(spec, profile)
            label = f"{(ctx.get('product') or {}).get('name', spec.stem)} under `{profile.name}`"
            if findings:
                gaps[f"the build does not resolve: {findings[0]}"].append(label)
                continue
            for gap in json.loads(render_context(ctx)["manifest.json"])["gaps"]:
                gaps[gap].append(label)
    return dict(sorted(gaps.items())), profiles


def evidence(result, platform):
    """(group, label, status, detail) per test that evidences this binding."""
    rows = []
    for (cls, method), slot in sorted(result.outcomes.items()):
        if platform in slot:
            status, detail = slot[platform]
        elif set(slot) == {None}:
            status, detail = slot[None]
        elif None in slot and slot[None][0] != "pass":  # failed outside its per-binding subtests
            status, detail = slot[None]
        else:
            continue
        explicit = platform in slot or cls in GROUPS
        group = GROUPS.get(cls, "Engine behaviour" if explicit else "Shared tooling")
        rows.append((group, result.labels[(cls, method)], status, detail))
    return rows


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def report(platform, result, title):
    binding, _ = load_binding(platform)
    rows = evidence(result, platform)
    gaps, profiles = build_gaps(platform)
    counts = {s: sum(1 for r in rows if r[2] == s) for s in RANK}
    problems = counts["fail"] + counts["error"] + counts["skip"]
    status = "standard" if not (problems or gaps or binding.gaps) else "draft"
    version = result.versions.get(platform)
    skipped = sorted({r[3] for r in rows if r[0] == "Engine behaviour" and r[2] == "skip"})
    lines = [MARKER, "", f"# {title} conformance report", "",
             f"Status: **{status}**. A binding is `standard` only when this report shows no failure, no "
             f"skipped test and no gap ([Platform Implementation Authoring Standard]"
             f"(../../design/core/IMPLEMENTATION_AUTHORING.md) §8.1). It is generated by "
             f"[`conformance.py`](../../tooling/bindings/conformance.py) from the tests, the binding's "
             f"declared gaps and the reference builds, and is never edited by hand.", "",
             f"{ENGINE_LINE} {version}." if version else
             f"{ENGINE_LINE} none: the engine tests did not run"
             + (f" ({'; '.join(skipped)})" if skipped else "") + ".", "",
             "| Outcome | Count |", "|---|---|",
             f"| Passed | {counts['pass']} |", f"| Failed | {counts['fail'] + counts['error']} |",
             f"| Skipped | {counts['skip']} |",
             f"| Gaps reported by the builds | {len(gaps)} |", f"| Gaps the binding declares | {len(binding.gaps)} |", ""]
    bad = [r for r in rows if r[2] in ("fail", "error")]
    if bad:
        lines += ["## Failures", "", "| Group | Test | Detail |", "|---|---|---|"]
        lines += [f"| {g} | {_cell(label)} | {_cell(detail)} |" for g, label, _, detail in bad] + [""]
    if counts["skip"]:
        lines += ["## Skipped", "", "A skipped test is a gap in coverage, never a pass.", "",
                  "| Group | Test | Reason |", "|---|---|---|"]
        lines += [f"| {g} | {_cell(label)} | {_cell(detail)} |" for g, label, s, detail in rows if s == "skip"] + [""]
    lines += ["## Gaps reported by the builds", "",
              "Every gap the reference specifications' manifests report on this platform, built under "
              + ", ".join(f"`{p.name}`" for p in profiles) + ".", ""]
    if gaps:
        lines += ["| Gap | Reported by |", "|---|---|"]
        lines += [f"| {_cell(gap)} | {_cell('; '.join(builds))} |" for gap, builds in gaps.items()] + [""]
    else:
        lines += ["None.", ""]
    lines += ["## Gaps the binding declares", "",
              "What no check can detect, declared in the `Gaps` field of [PLATFORM_PROFILE.md]"
              "(PLATFORM_PROFILE.md#binding-declarations).", ""]
    if binding.gaps:
        lines += ["| Area | Gap |", "|---|---|"]
        lines += [f"| {_cell(area)} | {_cell(text[:1].upper() + text[1:])}. |"
                  for area, text in binding.gaps.items()] + [""]
    else:
        lines += ["None.", ""]
    lines += ["## Evidence", ""]
    for group in ("Engine behaviour", "Rendering and portability", "Dialect", "Package", "Shared tooling"):
        mine = [r for r in rows if r[0] == group]
        if mine:
            lines += [f"### {group}", "", "| Test | Outcome |", "|---|---|"]
            lines += [f"| {_cell(label)} | {status} |" for _, label, status, _ in mine] + [""]
    return "\n".join(lines).rstrip() + "\n"


def gap_rows(text):
    """The gap table rows of a report."""
    body = text.split("## Gaps reported by the builds", 1)[-1].split("## Evidence", 1)[0]
    return {line for line in body.splitlines()
            if line.startswith("| ") and not line.startswith(("| Gap |", "| Area |"))}


def _normalise(text):
    return "\n".join(line for line in text.splitlines() if not line.startswith(ENGINE_LINE)).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed report differs")
    parser.add_argument("--output", type=Path, help="write the reports under this directory instead")
    parser.add_argument("--platform", action="append", help="report only this binding (repeatable)")
    args = parser.parse_args()
    result = run_tests(sys.stdout)
    titles = {"postgres": "PostgreSQL", "duckdb": "DuckDB", "teradata": "Teradata"}
    failed = bool(result.failures or result.errors or result.skipped)
    for platform in args.platform or platforms():
        text = report(platform, result, titles.get(platform, platform))
        committed = REPO / "implementation" / platform / "CONFORMANCE.md"
        if args.output:
            target = args.output / platform / "CONFORMANCE.md"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
        elif not args.check:
            committed.write_text(text, encoding="utf-8", newline="\n")
        if args.check:
            before = committed.read_text(encoding="utf-8") if committed.is_file() else ""
            if _normalise(before) != _normalise(text):
                failed = True
                new = sorted(gap_rows(text) - gap_rows(before))
                print(f"conformance: {committed.relative_to(REPO)} is out of date; regenerate it"
                      + (". Gaps it does not carry:\n  " + "\n  ".join(new) if new else ""), file=sys.stderr)
        print(f"conformance: {platform}: {text.split('Status: **')[1].split('**')[0]}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
