def ddl(e):
    fields = [f"    {n} {t}" for n, t, _ in columns(e)]
    if e.name.endswith('_keymap'):
        fields[0] = f"    {e.key} BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)"
        fields.append(f"    UNIQUE ({e.key}, {e.natural})")
    if e.qualified == 'observability.change_event':
        fields[0] = f"    {e.key} BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)"
    if e.schema == 'domain' and e.history:
        fields.append(f"    FOREIGN KEY ({e.key}, {e.natural}) REFERENCES {e.qualified}_keymap ({e.key}, {e.natural})")
    if e.schema == 'search':
        fields.append("    CHECK (array_ndims(embedding)=1 AND array_lower(embedding,1)=1 AND cardinality(embedding)=embedding_dimensions AND array_position(embedding,NULL) IS NULL)")
    fields.append(f"    PRIMARY KEY ({e.key}" + (", valid_from_dts)" if e.history else ")"))
    fields.extend("    " + x for x in e.constraints)
    vocabularies = {
        "scope_level": ("USER","TEAM","ORGANIZATION","AGENT"),
        "module_name": tuple(MODULES), "source_module": tuple(MODULES),
        "deployment_status": ("DEPLOYED","PLANNED","DEPRECATED"),
        "decision_status": ("PROPOSED","ACCEPTED","SUPERSEDED","DEPRECATED"),
        "decision_category": ("ARCHITECTURE","SCHEMA","NAMING","PERFORMANCE","SECURITY","INTEGRATION","OPERATIONAL"),
        "term_category": ("ENTITY","ATTRIBUTE","METRIC","BUSINESS_RULE","CLASSIFICATION","REFERENCE_CODE"),
        "complexity": ("SIMPLE","MODERATE","COMPLEX","ADVANCED"),
        "session_status": ("ACTIVE","COMPLETED","ABANDONED"),
        "interaction_type": ("QUERY","ACTION","DECISION","EXPLANATION"),
        "outcome_status": ("SUCCESS","PARTIAL","FAILED"),
        "run_status": ("SUCCESS","FAILED","PARTIAL","RUNNING"),
        "scope_kind": ("PRODUCT","MODULE","ENTITY","PATTERN","CAPABILITY"),
        "area_status": ("pass","fail","partial","not-validated","no-evidence"),
        "confidence": ("strong","partial","weak","unknown"),
        "severity": ("INFO","WARNING","ERROR","CRITICAL"),
        "dataset_role": ("PRIMARY","JOINED"),
        "object_kind": ("ENTITY","COLUMN","METRIC"),
    }
    if e.name == "validation_check":
        vocabularies["status"] = ("PASSED","FAILED","ERROR")
    for name, _, _ in e.columns:
        if name in vocabularies:
            fields.append(f"    CHECK ({name} IN ({','.join(literal(x) for x in vocabularies[name])}))")
    if e.history:
        fields += ["    CHECK(valid_from_dts < valid_to_dts)",
                   "    CHECK(is_current = (valid_to_dts = 'infinity'::TIMESTAMPTZ))",
                   "    CHECK(is_deleted = (deleted_dts IS NOT NULL))"]
    sql = f"CREATE TABLE {e.qualified} (\n" + ",\n".join(fields) + "\n);\n"
    sql += f"COMMENT ON TABLE {e.qualified} IS {literal(e.description)};\n"
    for name, _, meaning in columns(e):
        sql += f"COMMENT ON COLUMN {e.qualified}.{name} IS {literal(meaning)};\n"
    # Runtime tables deliberately have no public view. Host API binds scope itself.
    if not e.runtime:
        exposed = e.columns + ([TEMPORAL[0]] if e.history else [])
        sql += f"CREATE VIEW {e.schema}.v_{e.name} AS SELECT " + ", ".join(c[0] for c in exposed)
        sql += f" FROM {e.qualified}"
        if e.history:
            sql += " WHERE is_current AND valid_to_dts='infinity'::TIMESTAMPTZ AND NOT is_deleted"
        sql += ";\n"
        sql += f"COMMENT ON VIEW {e.schema}.v_{e.name} IS {literal('Consumer contract: ' + e.description)};\n"
    if e.history:
        sql += f"CREATE FUNCTION {e.schema}.at_{e.name}(at_dts TIMESTAMPTZ) RETURNS SETOF {e.qualified} LANGUAGE SQL STABLE AS $$ SELECT * FROM {e.qualified} WHERE valid_from_dts <= at_dts AND at_dts < valid_to_dts AND NOT is_deleted; $$;\n"
        sql += f"CREATE UNIQUE INDEX ON {e.qualified} ({e.key}) WHERE is_current;\n"
        sql += f"ALTER TABLE {e.qualified} ADD EXCLUDE USING gist ({e.key} WITH =, tstzrange(valid_from_dts, valid_to_dts, '[)') WITH &&);\n"
    return sql + "\n"


