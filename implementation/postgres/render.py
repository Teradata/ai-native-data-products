def render_all():
    files = {}
    for module in MODULES:
        files[ROOT / f"modules/{module}/schema.sql"] = "-- Generated by implementation/postgres/render.py; edit model.py.\n" + "".join(ddl(e) for e in ENTITIES if e.schema == module)
    files[EXAMPLE / "registration.sql"] = "-- Generated deployment-time metadata; edit render.py.\n" + registration() + documentation()
    build = "-- Generated portable example. Run only in a new empty product database.\nBEGIN TRANSACTION;\nCREATE EXTENSION IF NOT EXISTS btree_gist;\nSET TimeZone='UTC';\n"
    build += "\n".join(f"CREATE SCHEMA {m};" for m in MODULES) + "\n"
    for module in ("memory", "semantic", "domain", "observability", "search", "prediction"):
        build += files[ROOT / f"modules/{module}/schema.sql"]
    for path in [ROOT / "modules/search/functions.sql", ROOT / "modules/semantic/discovery.sql",
                 ROOT / "patterns/validation/views.sql", EXAMPLE / "seed.sql"]:
        build += path.read_text(encoding="utf-8") + "\n"
    build += files[EXAMPLE / "registration.sql"]
    # The observations are synthetic historical facts; physical audit time is
    # the actual deployment transaction, never the fixture's business clock.
    build += "-- Record actual physical deployment audit instants.\n"
    build += "\n".join(f"UPDATE {e.qualified} SET created_dts=current_timestamp,updated_dts=current_timestamp;" for e in ENTITIES)
    build += (ROOT / "patterns/access-layer/grants.sql").read_text(encoding="utf-8")
    build += "\nCOMMIT;\n"
    files[EXAMPLE / "build.sql"] = build
    from checks import profile
    files[ROOT / "patterns/validation/conformance.sql"] = (
        "-- Generated from checks.py; read-only violations counts. Zero is pass.\n" +
        "\n".join(f"SELECT {literal(c.test_id)} AS test_id, count(*) AS violations FROM ({c.sql}) defects;" for c in profile()) + "\n")
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in render_all().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale generated SQL: " + ", ".join(stale))


if __name__ == "__main__":
    main()
