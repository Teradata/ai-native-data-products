def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return str(value).upper()
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def columns(e):
    return e.columns + (TEMPORAL if e.history else []) + AUDIT


def insert(e, values, start=EPOCH, end="infinity", deleted=False):
    values = dict(values)
    if e.history:
        values.update(valid_from_dts=start, valid_to_dts=end, is_current=end == "infinity",
                      is_deleted=deleted, deleted_dts=start if deleted else None)
    values.update(created_dts=EPOCH, updated_dts=EPOCH)
    names = ", ".join(values)
    return f"INSERT INTO {e.qualified} ({names}) VALUES ({', '.join(literal(v) for v in values.values())});\n"


