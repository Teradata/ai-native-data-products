"""The PostgreSQL dialect: what PostgreSQL 16 does differently from the portable defaults.

Identity columns, array vectors, exclusion constraints for temporal non-overlap, SQL
functions for point-in-time reads, roles, row-level security and advisory locks.
"""
from portable_dialect import PortableDialect


class PostgresDialect(PortableDialect):
    table_gap = "\n\n"

    def phase_containers(self):
        """The btree_gist extension the exclusion constraints need, then each schema with its
        purpose."""
        purpose = self.literal(f"Container of the {self.ctx['product']['name']} data product, "
                               "as the organisation profile places it.")
        out = []
        for c in self.ctx["containers"]:
            if c["holds_objects"] and not c["adopted"]:
                out += [f"CREATE SCHEMA {self.ident(c['name'])};", f"COMMENT ON SCHEMA {self.ident(c['name'])} IS {purpose};"]
        return "CREATE EXTENSION IF NOT EXISTS btree_gist;\n\n" + "\n".join(out)

    def key_default(self, x, col):
        return " GENERATED BY DEFAULT AS IDENTITY" if x["generated_key"] else ""

    def column_checks(self, x, col):
        if not col.get("dimensions"):
            return ""
        n = self.ident(col["physical_name"])
        return (f" CHECK (array_ndims({n}) = 1 AND cardinality({n}) = {col['dimensions']} "
                f"AND array_position({n}, NULL) IS NULL)")

    def history_constraints(self, x):
        """One open version per identity, and no overlapping intervals, enforced."""
        t, cn = self.qualified(x["objects"]["table"]), x["column_names"]
        keys = "".join(f"{self.ident(k)} WITH =, " for k in x["version_columns"])
        exclude = (f"    {keys}tstzrange({self.ident(cn['valid_from_dts'])}, {self.ident(cn['valid_to_dts'])}, '[)') WITH &&")
        if x["bitemporal"]:
            exclude += (f",\n    tstzrange({self.ident(cn['transaction_from_dts'])}, "
                        f"{self.ident(cn['transaction_to_dts'])}, '[)') WITH &&")
        return (f"CREATE UNIQUE INDEX ON {t} ({self.cols(x['version_columns'])}) WHERE {self.ident(cn['is_current'])};\n"
                f"ALTER TABLE {t} ADD EXCLUDE USING gist (\n{exclude});")

    def point_in_time(self, x):
        f, t = self.qualified(x["objects"]["function"]), self.qualified(x["objects"]["table"])
        args = "valid_at TIMESTAMPTZ" + (", known_at TIMESTAMPTZ" if x["bitemporal"] else "")
        types = "TIMESTAMPTZ" + (", TIMESTAMPTZ" if x["bitemporal"] else "")
        takes = " Takes the valid-time and known-time instants." if x["bitemporal"] else " Takes the valid-time instant."
        return "\n".join([f"CREATE FUNCTION {f}({args})", f"RETURNS SETOF {t} LANGUAGE SQL STABLE",
                          "SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $body$",
                          f"SELECT * FROM {t} WHERE {self.at(x)};", "$body$;",
                          f"COMMENT ON FUNCTION {f}({types}) IS "
                          f"{self.literal('Point-in-time reconstruction of ' + x['description'] + takes)};"])


    def check_entity_metadata(self, entity):
        t = entity["objects"]["table"]
        return "\n".join([
            self.expected_columns(entity),
            "LEFT JOIN information_schema.columns actual",
            f"  ON actual.table_schema = {self.literal(t['container'])} AND actual.table_name = {self.literal(t['name'])}",
            " AND actual.column_name = expected.column_name",
            "LEFT JOIN pg_catalog.pg_namespace ns ON ns.nspname = actual.table_schema",
            "LEFT JOIN pg_catalog.pg_class tab ON tab.relnamespace = ns.oid AND tab.relname = actual.table_name",
            "LEFT JOIN pg_catalog.pg_attribute attr ON attr.attrelid = tab.oid AND attr.attname = actual.column_name",
            "WHERE actual.column_name IS NULL OR nullif(pg_catalog.col_description(tab.oid, attr.attnum), '') IS NULL"])

    def maintenance_lock(self, x, stable_key):
        t = x["objects"]["table"]
        return (f"SELECT pg_advisory_xact_lock(hashtextextended("
                f"{self.literal(t['container'] + '.' + t['name'] + ':' + str(stable_key))}, 0));")

    def check_product_comment_coverage(self):
        """Objects owned by an extension are not the product's to document and are skipped."""
        inside = self.owned_containers()
        not_extension = ("  AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend d WHERE d.classid = 'pg_catalog.{0}'::regclass "
                         "AND d.objid = {1}.oid AND d.deptype = 'e')")
        return "\n".join([
            "SELECT n.nspname AS container_name, 'schema' AS object_kind, n.nspname AS object_name, NULL::TEXT AS column_name",
            "FROM pg_catalog.pg_namespace n", f"WHERE n.nspname IN ({inside})",
            "  AND nullif(btrim(pg_catalog.obj_description(n.oid, 'pg_namespace')), '') IS NULL",
            "UNION ALL",
            "SELECT n.nspname, CASE c.relkind WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized view' "
            "WHEN 'f' THEN 'foreign table' ELSE 'table' END,",
            "       c.relname, NULL",
            "FROM pg_catalog.pg_class c INNER JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace",
            f"WHERE n.nspname IN ({inside}) AND c.relkind IN ('r', 'p', 'v', 'm', 'f')",
            not_extension.format("pg_class", "c"),
            "  AND nullif(btrim(pg_catalog.obj_description(c.oid, 'pg_class')), '') IS NULL",
            "UNION ALL",
            "SELECT n.nspname, 'column', c.relname, a.attname", "FROM pg_catalog.pg_attribute a",
            "INNER JOIN pg_catalog.pg_class c ON c.oid = a.attrelid",
            "INNER JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace",
            f"WHERE n.nspname IN ({inside}) AND c.relkind IN ('r', 'p', 'v', 'm', 'f') AND a.attnum > 0 AND NOT a.attisdropped",
            not_extension.format("pg_class", "c"),
            "  AND nullif(btrim(pg_catalog.col_description(c.oid, a.attnum)), '') IS NULL",
            "UNION ALL",
            "SELECT n.nspname, 'function', p.proname, NULL",
            "FROM pg_catalog.pg_proc p INNER JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace",
            f"WHERE n.nspname IN ({inside})", not_extension.format("pg_proc", "p"),
            "  AND nullif(btrim(pg_catalog.obj_description(p.oid, 'pg_proc')), '') IS NULL"])

    def versions_differ(self, a, b, x):
        cn = x["column_names"]
        tx = f", {{}}.{self.ident(cn['transaction_from_dts'])}" if x["bitemporal"] else ""
        vf = self.ident(cn["valid_from_dts"])
        return f"({a}.{vf}{tx.format(a)}) <> ({b}.{vf}{tx.format(b)})"

    def phase_access(self):
        """The access tiers (Access Layer): the principals the build context names, created where
        the profile says the build creates them. Read and agent tiers reach consumer views and
        functions only; the agent tier also writes its write targets, and reads and writes
        runtime Memory under row-level scope; the admin tier maintains everything. A
        container-level grant reaches only a container that holds no tables, so a grant never
        reaches a table."""
        ctx, ident, q = self.ctx, self.ident, self.qualified
        tiers = ctx["principals"]
        read, agent, admin = (ident(tiers[t]["name"]) for t in ("ROLE_READ", "ROLE_AGENT", "ROLE_ADMIN"))
        sections = ["\n".join(f"CREATE ROLE {ident(tiers[t]['name'])} NOLOGIN;"
                              for t in ("ROLE_READ", "ROLE_AGENT", "ROLE_ADMIN") if tiers[t]["create"])]
        for k in ctx["containers"]:
            if k["holds_objects"] and not k["adopted"]:
                s = ident(k["name"])
                sections.append("\n".join([
                    f"REVOKE ALL ON SCHEMA {s} FROM PUBLIC;", f"REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA {s} FROM PUBLIC;",
                    f"ALTER DEFAULT PRIVILEGES IN SCHEMA {s} REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;",
                    f"GRANT USAGE ON SCHEMA {s} TO {read}, {agent}, {admin};",
                    f"GRANT ALL ON ALL TABLES IN SCHEMA {s} TO {admin};",
                    f"GRANT ALL ON ALL SEQUENCES IN SCHEMA {s} TO {admin};",
                    f"GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA {s} TO {admin};"]))
        whole = self.whole_containers()
        sections.append("\n".join(f"GRANT SELECT ON ALL TABLES IN SCHEMA {ident(k)} TO {read}, {agent};" for k in whole))
        sections.append("\n".join(f"GRANT SELECT ON {q(x['objects']['consumer_view'])} TO {read}, {agent};"
                                  for x in self.relations() if "consumer_view" in x["objects"]
                                  and x["objects"]["consumer_view"]["container"] not in whole))
        sections.append("\n".join(f"GRANT EXECUTE ON FUNCTION {q(x['objects']['function'])} TO {read}, {agent};"
                                  for x in self.relations() if "function" in x["objects"]))
        sections.append("\n".join(f"GRANT EXECUTE ON FUNCTION {q(b['objects']['function'])} TO {read}, {agent};"
                                  for b in ctx["embeddings"] if "function" in b["objects"]))
        for x in self.relations():
            if "table" not in x["objects"] or x["objects"]["table"].get("primary_role") != "WRITE_TARGET":
                continue
            t = q(x["objects"]["table"])
            if x["runtime"]:
                cn = x["column_names"]
                scope = f"{ident(cn['scope_level'])} = 'USER' AND {ident(cn['scope_identifier'])} = session_user"
                sections.append("\n".join([
                    f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;", f"CREATE POLICY runtime_user ON {t} TO {agent}",
                    f"    USING ({scope})", f"    WITH CHECK ({scope});",
                    f"CREATE POLICY runtime_admin ON {t} TO {admin} USING (TRUE) WITH CHECK (TRUE);",
                    f"GRANT SELECT, INSERT, UPDATE ON {t} TO {agent};"]))
            else:
                sections.append(f"GRANT INSERT ON {t} TO {agent};")
        return "\n\n".join(s for s in sections if s)

    def similarity(self, b):
        store = self.named(b["store"])
        sc, v, dims = store["column_names"], "e." + self.ident(b["vector_column"]), b["dimensions"]
        score = {"cosine": f"sum({v}[i] * query_vector[i]) / nullif(sqrt(sum({v}[i] ^ 2)) * sqrt(sum(query_vector[i] ^ 2)), 0)",
                 "dot": f"sum({v}[i] * query_vector[i])",
                 "euclidean": f"1.0 / (1.0 + sqrt(sum(({v}[i] - query_vector[i]) ^ 2)))"}.get(
            b["similarity"], f"1.0 / (1.0 + sum(abs({v}[i] - query_vector[i])))")
        f = self.qualified(b["objects"]["function"])
        note = (f"Similarity search over the {b['name']} embedding of {b['entity']}. "
                "Takes a query vector and a result limit (maximum 1000).")
        return "\n".join(
            [f"CREATE FUNCTION {f}(query_vector DOUBLE PRECISION[], result_limit INTEGER)",
             "RETURNS TABLE(entity_id BIGINT, similarity DOUBLE PRECISION)", "LANGUAGE SQL STABLE AS $body$",
             "SELECT ranked.entity_id, ranked.similarity FROM (",
             f"    SELECT e.{self.ident(sc['entity_id'])} AS entity_id,",
             f"           (SELECT {score} FROM generate_series(1, {dims}) g(i)) AS similarity",
             f"    FROM {self.qualified(store['objects']['consumer_view'])} e"]
            + self.similarity_filters(b, sc)
            + [f"      AND cardinality(query_vector) = {dims} AND array_ndims(query_vector) = 1",
               "      AND array_position(query_vector, NULL) IS NULL"]
            + self.similarity_tail(b)
            + ["$body$;", f"COMMENT ON FUNCTION {f}(DOUBLE PRECISION[], INTEGER) IS {self.literal(note)};"])


DIALECT = PostgresDialect
