    def relationship_paths(self, paths, rel, relcol):
        """Teradata has no arrays, and a view built on a recursive query is not relied on here,
        so each path length up to the standard's bound is its own branch and each position in
        the path its own row set, one branch per (length, position). A path never returns to
        an entity it has passed through."""
        t, u, ident = rel["column_names"], relcol["column_names"], self.ident
        r_tbl, c_tbl = self.qualified(rel["objects"]["table"]), self.qualified(relcol["objects"]["table"])

        def cast(expr, width=400):
            return f"CAST({expr} AS VARCHAR({width}))"

        join = f" INNER JOIN {c_tbl} c ON c.{ident(u['relationship_id'])} = r.{ident(t['relationship_id'])}"
        active = f" WHERE r.{ident(t['is_active'])} = 1 AND c.{ident(u['is_active'])} = 1"
        edges = "\n".join([
            f"(SELECT r.{ident(t['relationship_id'])} AS relationship_id, c.{ident(u['ordinal'])} AS key_ordinal,",
            "        CAST('FORWARD' AS VARCHAR(7)) AS direction,",
            f"        {cast('r.' + ident(t['source_entity']))} AS from_entity, {cast('c.' + ident(u['source_column']))} AS from_column,",
            f"        {cast('r.' + ident(t['target_entity']))} AS to_entity, {cast('c.' + ident(u['target_column']))} AS to_column",
            f" FROM {r_tbl} r", join, active, " UNION ALL",
            f" SELECT r.{ident(t['relationship_id'])}, c.{ident(u['ordinal'])}, CAST('REVERSE' AS VARCHAR(7)),",
            f"        {cast('r.' + ident(t['target_entity']))}, {cast('c.' + ident(u['target_column']))},",
            f"        {cast('r.' + ident(t['source_entity']))}, {cast('c.' + ident(u['source_column']))}",
            f" FROM {r_tbl} r", join, active + ")"])
        steps = "\n".join([
            "(SELECT DISTINCT src.relationship_id, src.direction, src.from_entity, src.to_entity,",
            "        CAST(CAST(src.relationship_id AS VARCHAR(20)) || CASE src.direction WHEN 'FORWARD' THEN '>' "
            "ELSE '<' END AS VARCHAR(24)) AS leg",
            f" FROM {edges} src)"])
        names = [n for n, _ in self.PATHS_COLUMNS]
        out = [f"REPLACE VIEW {self.qualified(paths['objects']['consumer_view'])}", f"({self.cols(names)}) AS",
               "LOCKING ROW FOR ACCESS"]
        top = paths["max_hops"]
        for n in range(1, top + 1):
            for h in range(1, n + 1):
                legs = " || ".join(f"stp{k}.leg" for k in range(1, n + 1))
                out += [f"SELECT CAST({legs} AS VARCHAR(200)) AS path_id,",
                        f"       stp1.from_entity AS origin_entity, stp{n}.to_entity AS destination_entity,",
                        f"       CAST({n} AS INTEGER) AS hop_count, CAST({h} AS INTEGER) AS hop,",
                        "       edg.key_ordinal, edg.from_entity, edg.from_column, edg.to_entity, edg.to_column, "
                        "edg.relationship_id, edg.direction",
                        f"FROM {steps} stp1"]
                for k in range(2, n + 1):
                    distinct = "".join(f" AND stp{k}.to_entity <> stp{j}.to_entity" for j in range(1, k))
                    out += [f"INNER JOIN {steps} stp{k} ON stp{k}.from_entity = stp{k - 1}.to_entity",
                            f" AND stp{k}.to_entity <> stp1.from_entity{distinct}"]
                out.append(f"INNER JOIN {edges} edg ON edg.relationship_id = stp{h}.relationship_id "
                           f"AND edg.direction = stp{h}.direction")
                if not (n == top and h == n):
                    out.append("UNION ALL")
        return "\n".join(out) + ";"

    def lineage_graph(self, graph_view, lineage):
        d, ident, t = lineage["column_names"], self.ident, self.qualified(lineage["objects"]["table"])
        active = f"WHERE {ident(d['is_active'])} = 1 AND {ident(d['job_name'])} IS NOT NULL"
        return "\n".join([
            f"REPLACE VIEW {self.qualified(graph_view['objects']['consumer_view'])} AS", "LOCKING ROW FOR ACCESS",
            f"SELECT DISTINCT CAST(COALESCE({ident(d['source_container'])} || '.', '') || COALESCE({ident(d['source_table'])}, "
            f"{ident(d['source_system'])}) AS VARCHAR(400)) AS source_node,",
            f"       CAST({ident(d['job_name'])} AS VARCHAR(400)) AS target_node, CAST('produces' AS VARCHAR(20)) AS edge_type",
            f"FROM {t} {active}", "UNION",
            f"SELECT DISTINCT CAST({ident(d['job_name'])} AS VARCHAR(400)),",
            f"       CAST(COALESCE({ident(d['target_container'])} || '.', '') || {ident(d['target_table'])} AS VARCHAR(400)), 'produces'",
            f"FROM {t} {active};"])

    def lineage_run_latest(self, latest, lineage, run):
        d, r, ident = lineage["column_names"], run["column_names"], self.ident
        return "\n".join([
            f"REPLACE VIEW {self.qualified(latest['objects']['consumer_view'])} AS", "LOCKING ROW FOR ACCESS",
            f"SELECT d.{ident(d['lineage_id'])} AS lineage_id, d.{ident(d['source_table'])} AS source_table,",
            f"       d.{ident(d['target_table'])} AS target_table, d.{ident(d['job_name'])} AS job_name,",
            f"       r.{ident(r['run_dts'])} AS run_dts, r.{ident(r['run_status'])} AS run_status",
            f"FROM {self.qualified(lineage['objects']['table'])} d",
            f"LEFT JOIN {self.qualified(run['objects']['table'])} r ON r.{ident(r['lineage_id'])} = d.{ident(d['lineage_id'])}",
            f"WHERE d.{ident(d['is_active'])} = 1",
            f"QUALIFY ROW_NUMBER() OVER (PARTITION BY d.{ident(d['lineage_id'])}",
            f"                           ORDER BY r.{ident(r['run_dts'])} DESC, r.{ident(r['lineage_run_id'])} DESC) = 1;"])


