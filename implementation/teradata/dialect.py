"""The Teradata dialect: what Teradata Vantage does differently from the portable defaults.

Platform constants (PLATFORM_PROFILE section 7): a Flag is BYTEINT 0/1; a Vector is its
elements as little-endian 8-byte floats, which is what TD_VECTORDISTANCE reads, in the
VARBYTE the declared type sizes, checked to exactly that length; the open end of an interval
is the sentinel below, stated by every statement that opens a version and never a DEFAULT,
because the driver hangs parsing a zone-qualified literal in a CREATE TABLE DEFAULT; text
columns are UNICODE so prose is not untranslatable; a comment is held to the dictionary's
255 characters. DDL commits statement by statement, so a deployment is not one transaction.
"""
from portable_dialect import PortableDialect

SENTINEL = "TIMESTAMP '9999-12-31 23:59:59.999999+00:00'"
COMMENT_LIMIT = 255


class TeradataDialect(PortableDialect):
    open_end = SENTINEL
    now = "CURRENT_TIMESTAMP(6)"
    true, false = "1", "0"
    always = "1 = 1"
    column_comment_gap = "\n"

    def flag_test(self, expr):
        return f"{expr} = 1"

    def flag_not(self, expr):
        return f"{expr} = 0"

    def comment(self, text):
        return self.literal((text or "")[:COMMENT_LIMIT])

    def deploy(self, phases):
        """The phases in order: a failure stops the script and leaves what ran, which a
        redeploy replaces."""
        return "\n\n".join(f"-- {p['file']}\n{p['sql']}" for p in phases)

    def phase_containers(self):
        """Containers the build context places objects in, parents first. A parent database
        holds no objects and allocates its children's space; adopted containers already exist.
        Space comes from the `container_space` setting, per container that holds objects."""
        space = int(self.ctx["settings"]["container_space"])
        purpose = self.comment(f"Container of the {self.ctx['product']['name']} data product, "
                               "as the organisation profile places it.")
        containers = self.ctx["containers"]
        tops = []
        for c in containers:
            if c["parent"] or c["adopted"]:
                continue
            children = [k for k in containers if k["parent"] == c["name"]]
            perm = space * (max(len(children), 1) if not c["holds_objects"] else len(children) + 1)
            tops.append(f"CREATE DATABASE {self.ident(c['name'])} AS PERM = {perm};\n"
                        f"COMMENT ON DATABASE {self.ident(c['name'])} IS {purpose};")
        children = [f"CREATE DATABASE {self.ident(c['name'])} FROM {self.ident(c['parent'])} AS PERM = {space};\n"
                    f"COMMENT ON DATABASE {self.ident(c['name'])} IS {purpose};"
                    for c in containers if c["parent"] and not c["adopted"]]
        return "\n\n".join(p for p in ("\n\n".join(tops), "\n".join(children)) if p)

    # ---- tables -------------------------------------------------------------------------------
    @staticmethod
    def unicode(col):
        t = col["physical_type"]
        return " CHARACTER SET UNICODE" if "CHARACTER SET" not in t and (
            t.startswith("VARCHAR") or t.startswith("CLOB") or t == "JSON") else ""

    def column(self, x, col):
        name, keys = self.ident(col["physical_name"]), x["key_columns"]
        out = f"{name} {col['physical_type']}{self.unicode(col)}"
        if x["generated_key"] and col["physical_name"] in keys:
            out += " GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 NO CYCLE)"
        if self.required(col) or col["physical_name"] in keys or col["physical_name"] in x["version_columns"]:
            out += " NOT NULL"
        if (col.get("unique") and self.required(col) and not x["history"] and col["physical_name"] not in keys
                and not (x["kind"] == "Keymap" and col["physical_name"] in x["natural_columns"])):
            out += " UNIQUE"
        if col.get("members"):
            out += f" CHECK ({name} IN ({', '.join(self.literal(m) for m in col['members'])}))"
        if col["type"] == "Flag":
            out += f" CHECK ({name} IN (0, 1))"
        if col.get("dimensions"):
            out += f" CHECK (BYTES({name}) = {col['dimensions'] * 8})"
        return out

    def primary_index(self, x):
        """A keymap is read by its natural key, a versioned table keeps an identity's versions
        on one AMP, and anything else is read by its key."""
        if x["kind"] == "Keymap" and x["natural_columns"]:
            return f"UNIQUE PRIMARY INDEX ({self.cols(x['natural_columns'])})"
        if x["history"]:
            return f"PRIMARY INDEX ({self.cols(x['version_columns'])})"
        if x["key_columns"]:
            return f"UNIQUE PRIMARY INDEX ({self.cols(x['key_columns'])})"
        return f"PRIMARY INDEX ({self.ident(x['columns'][0]['physical_name'])})"

    def uniqueness(self, x):
        """One row per version of an identity, and a keymap's key, beyond the primary index."""
        cn = x["column_names"]
        if x["history"]:
            tx = f", {self.ident(cn['transaction_from_dts'])}" if x["bitemporal"] else ""
            return f",\n    UNIQUE ({self.cols(x['version_columns'])}, {self.ident(cn['valid_from_dts'])}{tx})"
        if x["kind"] == "Keymap" and x["key_columns"]:
            return f",\n    PRIMARY KEY ({self.cols(x['key_columns'])})"
        return ""

    def constraints(self, x):
        cn, out = x["column_names"], ""
        if x["history"]:
            out += f",\n    CHECK ({self.ident(cn['valid_from_dts'])} < {self.ident(cn['valid_to_dts'])})"
            if x["bitemporal"]:
                out += f",\n    CHECK ({self.ident(cn['transaction_from_dts'])} < {self.ident(cn['transaction_to_dts'])})"
        return out

    def table(self, x):
        columns = ",\n".join(f"    {self.column(x, col)}" for col in x["columns"])
        tail = self.uniqueness(x) + self.constraints(x)
        if x.get("identity", {}).get("keymap"):
            tail += (f",\n    FOREIGN KEY ({self.cols(x['key_columns'])}) REFERENCES WITH NO CHECK OPTION "
                     f"{self.keymap_of(x)}")
        return (f"CREATE MULTISET TABLE {self.qualified(x['objects']['table'])} (\n{columns}{tail}\n)\n"
                f"{self.primary_index(x)};")

    # ---- views ------------------------------------------------------------------------------
    def view(self, view, names, source, where, note, x):
        lines = [f"REPLACE VIEW {self.qualified(view)} ({self.cols(names)}) AS", "LOCKING ROW FOR ACCESS",
                 f"SELECT {self.cols(names)}", f"FROM {self.qualified(source)}" + (";" if where is None else ""),
                 *([f"WHERE {where};"] if where is not None else []),
                 f"COMMENT ON VIEW {self.qualified(view)} IS {self.comment(note)};"]
        return "\n".join(lines + self.view_column_comments(x, view, names))

    def phase_views(self):
        """The governed base view of every persisted relation, every column and row, then its
        consumer view: current rows only, the `view_columns` Semantic registers as the view's
        AccessColumn rows. Point-in-time reads go through the base view; Teradata SQL has no
        table functions. Views read with an access lock so a consumer never blocks a load."""
        rels = [x for x in self.relations() if x["relation"] == "table" and x.get("defined", True)]
        out = []
        for x in rels:
            if "base_view" in x["objects"]:
                names = [c["physical_name"] for c in x["columns"]]
                out.append(self.view(x["objects"]["base_view"], names, x["objects"]["table"], None,
                                     "Governed full contract: " + x["description"], x))
        for x in rels:
            if "consumer_view" in x["objects"]:
                names = [c["physical_name"] for c in x["view_columns"]]
                source = x["objects"].get("base_view", x["objects"]["table"])
                out.append(self.view(x["objects"]["consumer_view"], names, source, self.current(x),
                                     "Current consumer surface: " + x["description"], x))
        return "\n\n".join(out)


    # ---- checks: Teradata enforces none of the cross-row rules in its schema -------------------
    never = "1 = 0"

    def check_entity_metadata(self, entity):
        """Teradata has no table constructor and rejects a FROM-less SELECT in a union, so each
        expected column is one row of the dictionary's single-row version view."""
        x, t = entity, entity["objects"]["table"]
        rows = [f"    SELECT CAST({self.literal(col['physical_name'])} AS VARCHAR(128)) AS column_name FROM DBC.DBCInfoV "
                f"WHERE InfoKey = 'VERSION'" + (" UNION ALL" if i < len(x["columns"]) - 1 else "")
                for i, col in enumerate(x["columns"])]
        return "\n".join(["SELECT expected.column_name FROM ("] + rows + [
            ") AS expected", "LEFT JOIN DBC.ColumnsV actual",
            f"  ON TRIM(actual.DatabaseName) = {self.literal(t['container'])} AND TRIM(actual.TableName) = {self.literal(t['name'])}",
            " AND TRIM(actual.ColumnName) = expected.column_name",
            "WHERE actual.ColumnName IS NULL OR COALESCE(TRIM(actual.CommentString), '') = ''"])

    def current_flag_defects(self, x):
        cn, ident = x["column_names"], self.ident
        tx = f" AND a.{ident(cn['transaction_to_dts'])} = {SENTINEL}" if x["bitemporal"] else ""
        open_ = f"a.{ident(cn['valid_to_dts'])} = {SENTINEL}{tx}"
        return [f" OR (a.{ident(cn['is_current'])} = 1 AND NOT ({open_}))",
                f" OR (a.{ident(cn['is_current'])} = 0 AND {open_})"]

    def deletion_defects(self, x):
        cn, ident = x["column_names"], self.ident
        return [f" OR (a.{ident(cn['is_deleted'])} = 1 AND a.{ident(cn['deleted_dts'])} IS NULL)",
                f" OR (a.{ident(cn['is_deleted'])} = 0 AND a.{ident(cn['deleted_dts'])} IS NOT NULL)"]

    def timestamp_defects(self, x):
        return []

    def check_product_comment_coverage(self):
        """Every database the product creates, and every table, view, macro, procedure, function
        and column in one that holds objects. A container the product adopted is the
        organisation's, not the product's to document."""
        created, holding = self.owned_containers(holding=False), self.owned_containers()

        def text(expr, width=128):
            return f"CAST({expr} AS VARCHAR({width}))"
        return "\n".join([
            f"SELECT {text('TRIM(d.DatabaseName)')} AS container_name, CAST('database' AS VARCHAR(20)) AS object_kind,",
            f"       {text('TRIM(d.DatabaseName)')} AS object_name, CAST(NULL AS VARCHAR(128)) AS column_name",
            "FROM DBC.DatabasesV d", f"WHERE TRIM(d.DatabaseName) IN ({created})",
            "  AND COALESCE(TRIM(d.CommentString), '') = ''",
            "UNION ALL",
            f"SELECT {text('TRIM(t.DatabaseName)')},",
            "       CAST(CASE t.TableKind WHEN 'V' THEN 'view' WHEN 'M' THEN 'macro' WHEN 'P' THEN 'procedure' WHEN 'E' THEN 'procedure'",
            "                             WHEN 'F' THEN 'function' WHEN 'R' THEN 'function' WHEN 'A' THEN 'function' ELSE 'table' END AS VARCHAR(20)),",
            f"       {text('TRIM(t.TableName)')}, CAST(NULL AS VARCHAR(128))",
            "FROM DBC.TablesV t",
            f"WHERE TRIM(t.DatabaseName) IN ({holding}) AND t.TableKind IN ('T', 'O', 'V', 'M', 'P', 'E', 'F', 'R', 'A')",
            "  AND COALESCE(TRIM(t.CommentString), '') = ''",
            "UNION ALL",
            f"SELECT {text('TRIM(c.DatabaseName)')}, CAST('column' AS VARCHAR(20)), {text('TRIM(c.TableName)')},",
            f"       {text('TRIM(c.ColumnName)')}",
            "FROM DBC.ColumnsV c", "INNER JOIN DBC.TablesV t ON t.DatabaseName = c.DatabaseName AND t.TableName = c.TableName",
            f"WHERE TRIM(c.DatabaseName) IN ({holding}) AND t.TableKind IN ('T', 'O', 'V')",
            "  AND COALESCE(TRIM(c.CommentString), '') = ''"])

    def check_module_semantic(self, module):
        meta = self.named("EntityMetadata")
        c, ident = meta["column_names"], self.ident
        return "\n".join([
            "SELECT TRIM(t.DatabaseName) AS container_name, TRIM(t.TableName) AS table_name FROM DBC.TablesV t",
            f"LEFT JOIN {self.qualified(meta['objects']['table'])} e",
            f"  ON e.{ident(c['container_name'])} = TRIM(t.DatabaseName) AND e.{ident(c['table_name'])} = TRIM(t.TableName)",
            "WHERE t.TableKind IN ('T', 'O')",
            f"  AND {self.in_product('TRIM(t.DatabaseName)', 'TRIM(t.TableName)')}",
            f"  AND e.{ident(c['entity_name'])} IS NULL"])

    # ---- the Semantic metadata contract: every check returns the object_identity at fault and
    # the defect, each cast to a stated width because a union takes its widths from its first
    # branch; REGEXP_SIMILAR matches the whole string, and 'c' makes it case-sensitive ---------
    @staticmethod
    def who(expr):
        return f"CAST({expr} AS VARCHAR(500))"

    def what(self, text):
        return f"CAST({self.literal(text)} AS VARCHAR(100))"

    def contiguous(self, alias, ordinal):
        o = f"{alias}.{ordinal}"
        return f"COUNT(DISTINCT {o}) <> COUNT(*) OR MIN({o}) <> 1 OR MAX({o}) <> COUNT(*)"

    @staticmethod
    def has_column(alias, container, obj, column):
        """True when `alias` names a dictionary column for the given container, object and column."""
        return (f"TRIM({alias}.DatabaseName) = {container} AND TRIM({alias}.TableName) = {obj} "
                f"AND TRIM({alias}.ColumnName) = {column}")

    def similar(self, expr, pattern):
        return f"COALESCE(REGEXP_SIMILAR({expr}, '{pattern}', 'c'), 0) <> 1"

    def check_contract_identity(self):
        c, who, what = self.col, self.who, self.what
        en, active, mn = c("EntityMetadata", "entity_name"), c("EntityMetadata", "is_active"), c("EntityMetadata", "module_name")
        oi, a_active = c("AccessObject", "object_identity"), c("AccessObject", "is_active")
        em, ao = self.tbl("EntityMetadata"), self.tbl("AccessObject")
        return "\n".join([
            f"SELECT {who('e.' + en)} AS object_identity, {what('entity identity is not module.entity in its own module')} AS defect",
            f"FROM {em} e", f"WHERE e.{active} = 1",
            f"  AND ({self.similar('e.' + en, '[a-z][a-z0-9_]*[.][a-z][a-z0-9_]*')}",
            f"       OR SUBSTR(e.{en}, 1, CHARACTER_LENGTH(e.{mn}) + 1)", f"          <> LOWER(e.{mn}) || '.')",
            "UNION ALL",
            f"SELECT {who('e.' + en)}, {what('entity identity is registered more than once')}",
            f"FROM {em} e", f"WHERE e.{active} = 1", f"GROUP BY e.{en}", "HAVING COUNT(*) > 1",
            "UNION ALL",
            f"SELECT {who('a.' + oi)}, {what('access identity breaks the grammar')}",
            f"FROM {ao} a", f"WHERE a.{a_active} = 1",
            f"  AND {self.similar('a.' + oi, '[a-z][a-z0-9_]*[.][a-z][a-z0-9_]*:(base|governed|current|history)')}",
            f"  AND {self.similar('a.' + oi, '[a-z][a-z0-9_]*:[a-z][a-z0-9_]*')}",
            f"  AND {self.similar('a.' + oi, 'composite:[a-z][a-z0-9_]*')}",
            "UNION ALL",
            f"SELECT {who('a.' + oi)}, {what('single-entity identity does not match its entity and surface')}",
            f"FROM {ao} a", f"WHERE a.{a_active} = 1 AND a.{c('AccessObject', 'represents_entity')} IS NOT NULL",
            f"  AND a.{oi} <> a.{c('AccessObject', 'represents_entity')} || ':' ||",
            f"      CASE a.{c('AccessObject', 'object_type')} WHEN 'TABLE' THEN 'base' WHEN 'BASE_VIEW' THEN 'governed'",
            "           WHEN 'CONSUMER_VIEW' THEN 'current' ELSE 'history' END"])

    def check_contract_keys(self):
        c, who, what = self.col, self.who, self.what
        em, kd, kc = self.tbl("EntityMetadata"), self.tbl("KeyDefinition"), self.tbl("KeyColumn")
        en, kn = c("EntityMetadata", "entity_name"), c("KeyDefinition", "key_name")
        k_active, c_active = c("KeyDefinition", "is_active"), c("KeyColumn", "is_active")
        entity_of = f"INNER JOIN {em} e ON e.{self.pk('EntityMetadata')} = k.{c('KeyDefinition', 'entity_id')}"
        key = f"e.{en} || '#' || k.{kn}"
        return "\n".join([
            f"SELECT {who('e.' + en)} AS object_identity, {what('entity has no key definition')} AS defect",
            f"FROM {em} e", f"WHERE e.{c('EntityMetadata', 'is_active')} = 1",
            f"  AND NOT EXISTS (SELECT 1 FROM {kd} k",
            f"                  WHERE k.{c('KeyDefinition', 'entity_id')} = e.{self.pk('EntityMetadata')} AND k.{k_active} = 1)",
            "UNION ALL",
            f"SELECT {who(key)}, {what('key has no columns')}",
            f"FROM {kd} k", entity_of, f"WHERE k.{k_active} = 1",
            f"  AND NOT EXISTS (SELECT 1 FROM {kc} c",
            f"                  WHERE c.{c('KeyColumn', 'key_definition_id')} = k.{self.pk('KeyDefinition')} AND c.{c_active} = 1)",
            "UNION ALL",
            f"SELECT {who(key)}, {what('key column ordinals do not run 1..n')}",
            f"FROM {kd} k", entity_of,
            f"INNER JOIN {kc} c ON c.{c('KeyColumn', 'key_definition_id')} = k.{self.pk('KeyDefinition')}",
            f"WHERE k.{k_active} = 1 AND c.{c_active} = 1", f"GROUP BY e.{en}, k.{kn}",
            f"HAVING {self.contiguous('c', c('KeyColumn', 'ordinal'))}",
            "UNION ALL",
            f"SELECT {who(key + ' || ' + chr(39) + '.' + chr(39) + ' || c.' + c('KeyColumn', 'column_name'))},",
            f"       {what('key column is absent from its entity')}",
            f"FROM {kc} c",
            f"INNER JOIN {kd} k ON k.{self.pk('KeyDefinition')} = c.{c('KeyColumn', 'key_definition_id')}",
            entity_of, f"WHERE c.{c_active} = 1",
            "  AND NOT EXISTS (SELECT 1 FROM DBC.ColumnsV i",
            f"                  WHERE {self.has_column('i', 'e.' + c('EntityMetadata', 'container_name'), 'e.' + c('EntityMetadata', 'table_name'), 'c.' + c('KeyColumn', 'column_name'))})"])

    def check_contract_relationships(self):
        c, who, what = self.col, self.who, self.what
        tr, rc, em = self.tbl("TableRelationship"), self.tbl("RelationshipColumn"), self.tbl("EntityMetadata")
        rn, r_active, c_active = c("TableRelationship", "relationship_name"), c("TableRelationship", "is_active"), c("RelationshipColumn", "is_active")
        rel_of = f"c.{c('RelationshipColumn', 'relationship_id')} = r.{self.pk('TableRelationship')}"
        en = c("EntityMetadata", "entity_name")
        ordinal = f"r.{rn} || '.' || CAST(c.{c('RelationshipColumn', 'ordinal')} AS VARCHAR(10))"
        return "\n".join([
            f"SELECT {who('r.' + rn)} AS object_identity, {what('relationship has no column pair')} AS defect",
            f"FROM {tr} r", f"WHERE r.{r_active} = 1",
            f"  AND NOT EXISTS (SELECT 1 FROM {rc} c", f"                  WHERE {rel_of}",
            f"                    AND c.{c_active} = 1)",
            "UNION ALL",
            f"SELECT {who('r.' + rn)}, {what('relationship ordinals do not run 1..n')}",
            f"FROM {tr} r", f"INNER JOIN {rc} c ON {rel_of}", f"WHERE r.{r_active} = 1 AND c.{c_active} = 1",
            f"GROUP BY r.{rn}", f"HAVING {self.contiguous('c', c('RelationshipColumn', 'ordinal'))}",
            "UNION ALL",
            f"SELECT {who('r.' + rn)}, {what('relationship names an unregistered entity')}",
            f"FROM {tr} r", f"WHERE r.{r_active} = 1",
            f"  AND (NOT EXISTS (SELECT 1 FROM {em} e WHERE e.{en} = r.{c('TableRelationship', 'source_entity')})",
            f"    OR NOT EXISTS (SELECT 1 FROM {em} e WHERE e.{en} = r.{c('TableRelationship', 'target_entity')}))",
            "UNION ALL",
            f"SELECT {who(ordinal)},", f"       {what('relationship column is absent from its entity')}",
            f"FROM {rc} c",
            f"INNER JOIN {tr} r ON r.{self.pk('TableRelationship')} = c.{c('RelationshipColumn', 'relationship_id')}",
            f"INNER JOIN {em} s ON s.{en} = r.{c('TableRelationship', 'source_entity')}",
            f"INNER JOIN {em} t ON t.{en} = r.{c('TableRelationship', 'target_entity')}",
            f"WHERE c.{c_active} = 1",
            "  AND (NOT EXISTS (SELECT 1 FROM DBC.ColumnsV i",
            f"                   WHERE {self.has_column('i', 's.' + c('EntityMetadata', 'container_name'), 's.' + c('EntityMetadata', 'table_name'), 'c.' + c('RelationshipColumn', 'source_column'))})",
            "    OR NOT EXISTS (SELECT 1 FROM DBC.ColumnsV i",
            f"                   WHERE {self.has_column('i', 't.' + c('EntityMetadata', 'container_name'), 't.' + c('EntityMetadata', 'table_name'), 'c.' + c('RelationshipColumn', 'target_column'))}))"])

    def check_contract_access_columns(self):
        """The view's columns are read from the dictionary."""
        c, who, what = self.col, self.who, self.what
        ao, ac, em = self.tbl("AccessObject"), self.tbl("AccessColumn"), self.tbl("EntityMetadata")
        oi, m_active, mc = c("AccessObject", "object_identity"), c("AccessColumn", "is_active"), c("AccessColumn", "column_name")
        obj_of = f"INNER JOIN {ao} a ON a.{self.pk('AccessObject')} = m.{c('AccessColumn', 'access_object_id')}"
        mapped = f"a.{oi} || '.' || m.{mc}"
        return "\n".join([
            f"SELECT {who('a.' + oi + ' || ' + chr(39) + '.' + chr(39) + ' || TRIM(i.ColumnName)')} AS object_identity, "
            f"{what('output column has no mapping')} AS defect",
            f"FROM {ao} a", "INNER JOIN DBC.ColumnsV i",
            f"   ON TRIM(i.DatabaseName) = a.{c('AccessObject', 'container_name')} AND TRIM(i.TableName) = a.{c('AccessObject', 'object_name')}",
            f"WHERE a.{c('AccessObject', 'is_active')} = 1 AND a.{c('AccessObject', 'object_type')} = 'CONSUMER_VIEW'",
            f"  AND EXISTS (SELECT 1 FROM {em} e WHERE e.{c('EntityMetadata', 'entity_name')} = a.{c('AccessObject', 'represents_entity')})",
            f"  AND NOT EXISTS (SELECT 1 FROM {ac} m",
            f"                  WHERE m.{c('AccessColumn', 'access_object_id')} = a.{self.pk('AccessObject')}",
            f"                    AND m.{mc} = TRIM(i.ColumnName) AND m.{m_active} = 1)",
            "UNION ALL",
            f"SELECT {who(mapped)},", f"       {what('mapping names a column the object does not have')}",
            f"FROM {ac} m", obj_of, f"WHERE m.{m_active} = 1",
            "  AND NOT EXISTS (SELECT 1 FROM DBC.ColumnsV i",
            f"                  WHERE {self.has_column('i', 'a.' + c('AccessObject', 'container_name'), 'a.' + c('AccessObject', 'object_name'), 'm.' + mc)})",
            "UNION ALL",
            f"SELECT {who(mapped)},", f"       {what('mapping column is repeated')}",
            f"FROM {ac} m", obj_of, f"WHERE m.{m_active} = 1", f"GROUP BY a.{oi}, m.{mc}", "HAVING COUNT(*) > 1",
            "UNION ALL",
            f"SELECT {who('a.' + oi)}, {what('mapping ordinals do not run 1..n')}",
            f"FROM {ac} m", obj_of, f"WHERE m.{m_active} = 1", f"GROUP BY a.{oi}",
            f"HAVING {self.contiguous('m', c('AccessColumn', 'ordinal'))}",
            "UNION ALL",
            f"SELECT {who(mapped)}, {what('non-derived mapping source is absent')}",
            f"FROM {ac} m", obj_of, f"WHERE m.{m_active} = 1 AND m.{c('AccessColumn', 'mapping_kind')} <> 'DERIVED'",
            f"  AND NOT EXISTS (SELECT 1 FROM {em} e", "                  INNER JOIN DBC.ColumnsV i",
            f"                     ON TRIM(i.DatabaseName) = e.{c('EntityMetadata', 'container_name')} AND "
            f"TRIM(i.TableName) = e.{c('EntityMetadata', 'table_name')}",
            f"                  WHERE e.{c('EntityMetadata', 'entity_name')} = m.{c('AccessColumn', 'source_entity')}",
            f"                    AND TRIM(i.ColumnName) = m.{c('AccessColumn', 'source_column')})"])

    def check_contract_composition(self):
        """Outer references stay in WHERE, never in a subquery's ON."""
        c, who, what = self.col, self.who, self.what
        cp, tr, em = self.tbl("AccessComposition"), self.tbl("TableRelationship"), self.tbl("EntityMetadata")
        co, active, role = c("AccessComposition", "composite_object"), c("AccessComposition", "is_active"), c("AccessComposition", "member_role")
        me, via, direction = c("AccessComposition", "member_entity"), c("AccessComposition", "via_relationship_id"), c("AccessComposition", "via_direction")
        seq, src, tgt = c("AccessComposition", "member_seq"), c("TableRelationship", "source_entity"), c("TableRelationship", "target_entity")
        member = f"c.{co} || '.' || c.{me}"
        return "\n".join([
            f"SELECT {who('c.' + co)} AS object_identity, {what('composite does not have exactly one anchor')} AS defect",
            f"FROM {cp} c", f"WHERE c.{active} = 1", f"GROUP BY c.{co}",
            f"HAVING SUM(CASE WHEN c.{role} = 'ANCHOR' THEN 1 ELSE 0 END) <> 1",
            "UNION ALL",
            f"SELECT {who('c.' + co)}, {what('member order does not run 1..n')}",
            f"FROM {cp} c", f"WHERE c.{active} = 1", f"GROUP BY c.{co}", f"HAVING {self.contiguous('c', seq)}",
            "UNION ALL",
            f"SELECT {who(member)},", f"       {what('member does not join to a prior member through its relationship')}",
            f"FROM {cp} c", f"LEFT OUTER JOIN {tr} r ON r.{self.pk('TableRelationship')} = c.{via}",
            f"WHERE c.{active} = 1 AND c.{role} <> 'ANCHOR'",
            f"  AND NOT EXISTS (SELECT 1 FROM {cp} p", f"                  WHERE p.{co} = c.{co}",
            f"                    AND p.{seq} < c.{seq}",
            f"                    AND ((c.{direction} = 'FORWARD'", f"                          AND r.{src} = p.{me}",
            f"                          AND r.{tgt} = c.{me})", f"                      OR (c.{direction} = 'REVERSE'",
            f"                          AND r.{tgt} = p.{me}", f"                          AND r.{src} = c.{me})))",
            "UNION ALL",
            f"SELECT {who(member)},", f"       {what('anchor carries a join, or the member names an unregistered entity')}",
            f"FROM {cp} c", f"WHERE c.{active} = 1", f"  AND ((c.{role} = 'ANCHOR'",
            f"        AND (c.{via} IS NOT NULL OR c.{direction} IS NOT NULL))",
            f"    OR NOT EXISTS (SELECT 1 FROM {em} e",
            f"                   WHERE e.{c('EntityMetadata', 'entity_name')} = c.{me}))"])

    # ---- access, and statistics ---------------------------------------------------------------
    def phase_implied_grants(self):
        """The grants the placement makes necessary (Organisation Profile Standard §2): a view in
        one database compiles, and serves its readers, only once that database holds SELECT WITH
        GRANT OPTION on the database it reads; without it view creation fails with [5315]. Each
        pair comes from what a view reads; never a database to itself."""
        pairs = []
        for x in self.relations():
            objects = x["objects"]
            if "table" not in objects:
                continue
            if "base_view" in objects:
                pairs.append((objects["table"]["container"], objects["base_view"]["container"]))
            if "consumer_view" in objects:
                source = objects.get("base_view", objects["table"])
                pairs.append((source["container"], objects["consumer_view"]["container"]))
        for v in self.ctx["relations"]:
            if v["relation"] != "view":
                continue
            for x in self.ctx["relations"]:
                if x["relation"] == "table" and x["module"] in ("semantic", "observability") and "table" in x["objects"]:
                    pairs.append((x["objects"]["table"]["container"], v["objects"]["consumer_view"]["container"]))
        return "\n".join(f"GRANT SELECT ON {self.ident(s)} TO {self.ident(t)} WITH GRANT OPTION;"
                         for s, t in dict.fromkeys(pairs) if s != t)

    WHO = {"ROLE_READ": "analyst and BI consumer role", "ROLE_AGENT": "AI agent and automated tool role",
           "ROLE_ADMIN": "owner and data steward role"}

    def phase_access(self):
        """The access tiers (Access Layer), once every object exists. Read and agent tiers reach
        consumer views, the history of versioned relations through their governed base views,
        and the similarity procedures; the agent tier also writes its write targets; the admin
        tier maintains every database with the rights a role may hold. A role comment names who
        the role is for and never what it reaches."""
        ctx, ident, q = self.ctx, self.ident, self.qualified
        tiers = ctx["principals"]
        read, agent, admin = (ident(tiers[t]["name"]) for t in ("ROLE_READ", "ROLE_AGENT", "ROLE_ADMIN"))
        whole = self.whole_containers()

        def both(obj, verb="SELECT"):
            return f"GRANT {verb} ON {obj} TO {read};\nGRANT {verb} ON {obj} TO {agent};"

        sections = [
            "\n".join(f"CREATE ROLE {ident(tiers[t]['name'])};\nCOMMENT ON ROLE {ident(tiers[t]['name'])} IS "
                      f"{self.comment(ctx['product']['name'] + ' data product - ' + self.WHO[t] + '.')};"
                      for t in ("ROLE_READ", "ROLE_AGENT", "ROLE_ADMIN") if tiers[t]["create"]),
            "\n".join(f"GRANT SELECT, INSERT, UPDATE, DELETE, CREATE TABLE, DROP TABLE, CREATE VIEW, DROP VIEW, STATISTICS "
                      f"ON {ident(k['name'])} TO {admin};" for k in ctx["containers"] if k["holds_objects"] and not k["adopted"]),
            "\n".join(both(ident(k)) for k in whole),
            "\n".join(both(q(x["objects"]["consumer_view"])) for x in self.relations()
                      if "consumer_view" in x["objects"] and x["objects"]["consumer_view"]["container"] not in whole),
            "\n".join(both(q(x["objects"]["base_view"])) for x in self.relations()
                      if x["history"] and "consumer_view" in x["objects"] and "base_view" in x["objects"]
                      and x["objects"]["base_view"]["container"] not in whole),
            "\n".join(both(q(b["objects"]["procedure"]), "EXECUTE PROCEDURE") for b in ctx["embeddings"]
                      if "procedure" in b["objects"]),
            "\n".join(f"GRANT {'SELECT, INSERT, UPDATE' if x['runtime'] else 'INSERT'} ON {q(x['objects']['table'])} TO {agent};"
                      for x in self.relations()
                      if "table" in x["objects"] and x["objects"]["table"].get("primary_role") == "WRITE_TARGET")]
        return "\n\n".join(s for s in sections if s)

    def phase_statistics(self):
        """Statistics on the columns the optimiser joins and filters on (PLATFORM_PROFILE section
        6): the key and versioning columns and the temporal predicates of every persisted relation."""
        out = []
        for x in self.tables():
            cn = x["column_names"]
            stats = list(dict.fromkeys(x["key_columns"] + x["version_columns"]))
            stats += [cn[n] for n in ("is_current", "is_deleted", "valid_from_dts", "transaction_from_dts") if n in cn]
            out.append(f"COLLECT STATISTICS {', '.join(f'COLUMN ({self.ident(c)})' for c in stats)} "
                       f"ON {self.qualified(x['objects']['table'])};")
        return "\n\n".join(out)

    # ---- similarity search ---------------------------------------------------------------------
    MEASURES = {"cosine": "cosine", "dot": "dotproduct", "euclidean": "euclidean", "manhattan": "manhattan"}

    def inner(self, text):
        """A text literal written inside the dynamic SQL's own literal: its quotes doubled twice."""
        return self.literal(text).replace("'", "''")

    def similarity(self, b):
        """TD_VECTORDISTANCE is a table operator: it cannot sit in a view or a SQL function, and
        it takes no bind or macro parameter inside its ON clauses. So the procedure writes the
        query vector into the request as a hex literal (left-padded, since FROM_BYTES drops
        leading zero digits) and runs it as dynamic SQL, returning one result set of
        (entity_id, similarity). A query vector of the wrong length, or a limit of zero, returns
        no rows. Cosine and dot are 1 - distance, euclidean and manhattan 1 / (1 + distance)."""
        store = self.named(b["store"])
        sc, ident = store["column_names"], self.ident
        vector = next(c for c in store["columns"] if c["physical_name"] == b["vector_column"])
        width = int(b["dimensions"]) * 8
        score = "1 - d.distance" if b["similarity"] in ("cosine", "dot") else "1 / (1 + d.distance)"
        lines = [
            f"REPLACE PROCEDURE {self.qualified(b['objects']['procedure'])} (IN query_vector {vector['physical_type']}, "
            "IN result_limit INTEGER)",
            "DYNAMIC RESULT SETS 1", "BEGIN",
            f"    DECLARE query_text VARCHAR({2 * width + 4000});",
            "    DECLARE top_n INTEGER DEFAULT 0;",
            "    DECLARE results CURSOR WITH RETURN ONLY FOR prepared_query;",
            "    IF result_limit > 1000 THEN SET top_n = 1000;",
            "    ELSEIF result_limit > 0 THEN SET top_n = result_limit;",
            "    END IF;",
            f"    IF query_vector IS NULL OR BYTES(query_vector) <> {width} OR top_n = 0 THEN",
            "        SET query_text = 'SELECT CAST(NULL AS BIGINT) AS entity_id, CAST(NULL AS FLOAT) AS similarity "
            "FROM DBC.DBCInfoV WHERE 1 = 0';",
            "    ELSE",
            f"        SET query_text = 'SELECT d.target_id AS entity_id, CAST({score} AS FLOAT) AS similarity FROM TD_VECTORDISTANCE('",
            f"            || 'ON (SELECT e.{ident(sc['entity_id'])} AS entity_id, e.{ident(b['vector_column'])} AS embedding "
            f"FROM {self.qualified(store['objects']['consumer_view'])} e '",
            f"            || 'WHERE e.{ident(sc['source_attribute'])} = {self.inner(b['name'])}'"]
        if b.get("model"):
            lines.append(f"            || ' AND e.{ident(sc['embedding_model'])} = {self.inner(b['model'])}'")
        lines += [
            "            || ') AS TargetTable PARTITION BY ANY '",
            "            || 'ON (SELECT CAST(0 AS BIGINT) AS query_id, CAST(''' || "
            f"LPAD(CAST(FROM_BYTES(query_vector, 'base16') AS VARCHAR({2 * width})), {2 * width}, '0')",
            f"            || '''XB AS {vector['physical_type']}) AS embedding) AS ReferenceTable DIMENSION '",
            "            || 'USING TargetIDColumn(''entity_id'') TargetFeatureColumns(''embedding'') "
            "RefIDColumn(''query_id'') RefFeatureColumns(''embedding'') '",
            f"            || 'DistanceMeasure(''{self.MEASURES[b['similarity']]}'') TopK(1)) AS d'"]
        if b.get("threshold"):
            lines.append(f"            || ' WHERE {score} >= {b['threshold']}'")
        note = (f"Similarity search over the {b['name']} embedding of {b['entity']}. Takes a query vector and a "
                "result limit (maximum 1000); returns entity_id and similarity.")
        lines += [
            f"            || ' QUALIFY ROW_NUMBER() OVER (ORDER BY {score} DESC, d.target_id) <= ' || TRIM(top_n)",
            "            || ' ORDER BY similarity DESC, entity_id';",
            "    END IF;", "    PREPARE prepared_query FROM query_text;", "    OPEN results;", "END;",
            f"COMMENT ON PROCEDURE {self.qualified(b['objects']['procedure'])} IS {self.comment(note)};"]
        return "\n".join(lines)

    def similarity_recipe(self, r, b):
        return f"CALL {self.qualified(b['objects']['procedure'])}(?, 10)"

    def phase_similarity(self):
        """A database's creator is not granted CREATE PROCEDURE on it, so where the target names
        the `deploying_user`, that user is granted it on each database that holds a procedure."""
        procedures = [b for b in self.ctx["embeddings"] if "procedure" in b["objects"]]
        user, out = self.ctx["settings"]["deploying_user"], []
        if procedures and user != "none":
            containers = list(dict.fromkeys(b["objects"]["procedure"]["container"] for b in procedures))
            out.append("\n".join(f"GRANT CREATE PROCEDURE ON {self.ident(c)} TO {self.ident(user)};" for c in containers))
        return "\n\n".join(out + [self.similarity(b) for b in procedures])

    # ---- the trust map: no WITH or ORDER BY in a view, so the steps are derived tables and the
    # latest-row choices are QUALIFY; a NULL in a union branch is typed, or the union fails -------
    TRUST_COLUMNS = PortableDialect.TRUST_COLUMNS[:-1] + [
        ("derived", "1 when the entry is derived from a legacy run that published no area records, otherwise 0.")]

    def trust_map(self, view, run, area, registry):
        r, a, p, ident = run["column_names"], area["column_names"], registry["column_names"], self.ident
        secs = int(round(self.ctx["quality"]["evidence_window_days"] * 86400))
        window = (f"CAST('{secs // 86400} {secs % 86400 // 3600:02d}:{secs % 3600 // 60:02d}:{secs % 60:02d}' "
                  "AS INTERVAL DAY(4) TO SECOND)")
        area_t, run_t = self.qualified(area["objects"]["table"]), self.qualified(run["objects"]["table"])
        product = "\n".join([
            f"(SELECT {ident(p['product_id'])} AS product_code,",
            f"        CASE WHEN TRIM({ident(p['trust_authoritative_producer'])}) = '' THEN NULL ELSE "
            f"{ident(p['trust_authoritative_producer'])} END AS producer_id",
            f" FROM {self.qualified(registry['objects']['table'])} WHERE {ident(p['is_active'])} = 1 AND {ident(p['is_deleted'])} = 0)"])
        evidence = "\n".join([
            f"(SELECT x.{ident(a['product_code'])} AS product_code, x.{ident(a['producer_id'])} AS producer_id,",
            f"        x.{ident(a['run_id'])} AS run_id, x.{ident(a['scope_kind'])} AS scope_kind, x.{ident(a['scope_id'])} AS scope_id,",
            f"        x.{ident(a['area_status'])} AS area_status, x.{ident(a['confidence'])} AS confidence,",
            f"        x.{ident(a['checks_expected'])} AS checks_expected, x.{ident(a['checks_ran'])} AS checks_ran,",
            f"        x.{ident(a['passed_count'])} AS passed_count, x.{ident(a['failed_count'])} AS failed_count,",
            f"        x.{ident(a['error_count'])} AS error_count, x.{ident(a['critical_failure_count'])} AS critical_failure_count,",
            f"        x.{ident(a['error_failure_count'])} AS error_failure_count,",
            f"        CAST(x.{ident(a['open_gaps'])} AS VARCHAR(4000)) AS open_gaps,",
            f"        CAST(x.{ident(a['recommended_action'])} AS VARCHAR(4000)) AS recommended_action,",
            f"        x.{ident(a['completed_dts'])} AS completed_dts, y.{ident(r['evidence_expires_dts'])} AS evidence_expires_dts,",
            "        0 AS derived",
            f" FROM {area_t} x",
            f" JOIN {run_t} y ON y.{ident(r['product_code'])} = x.{ident(a['product_code'])}",
            f"  AND y.{ident(r['producer_id'])} = x.{ident(a['producer_id'])} AND y.{ident(r['run_id'])} = x.{ident(a['run_id'])}",
            " UNION ALL",
            f" SELECT y.{ident(r['product_code'])}, y.{ident(r['producer_id'])}, y.{ident(r['run_id'])}, 'PRODUCT', y.{ident(r['product_code'])},",
            f"        CASE WHEN y.{ident(r['total_checks'])} = 0 THEN 'no-evidence'",
            f"             WHEN y.{ident(r['failed_count'])} = 0 AND y.{ident(r['error_count'])} = 0 THEN 'pass' ELSE 'fail' END,",
            f"        CASE WHEN y.{ident(r['total_checks'])} = 0 THEN 'unknown'",
            f"             WHEN y.{ident(r['critical_failure_count'])} + y.{ident(r['error_failure_count'])} > 0 THEN 'weak'",
            "             ELSE 'partial' END,",
            f"        y.{ident(r['total_checks'])}, y.{ident(r['total_checks'])}, y.{ident(r['passed_count'])}, y.{ident(r['failed_count'])},",
            f"        y.{ident(r['error_count'])}, y.{ident(r['critical_failure_count'])}, y.{ident(r['error_failure_count'])},",
            f"        'Derived from a run with no area records.', CAST(NULL AS VARCHAR(4000)), y.{ident(r['completed_dts'])}, "
            f"y.{ident(r['evidence_expires_dts'])}, 1",
            f" FROM {run_t} y",
            f" WHERE y.{ident(r['payload_schema_version'])} IN ({self.legacy_versions()})",
            f"   AND NOT EXISTS (SELECT 1 FROM {area_t} x WHERE x.{ident(a['product_code'])} = y.{ident(r['product_code'])}",
            f"                   AND x.{ident(a['producer_id'])} = y.{ident(r['producer_id'])} AND x.{ident(a['run_id'])} = y.{ident(r['run_id'])}))"])
        v = self.qualified(view["objects"]["consumer_view"])
        lines = [
            f"REPLACE VIEW {v} AS", "LOCKING ROW FOR ACCESS",
            "SELECT c.product_code, c.producer_id, c.run_id, c.scope_kind, c.scope_id, c.area_status,",
            "       CASE WHEN c.stale = 1 THEN 'unknown' ELSE c.confidence END AS confidence,",
            "       c.checks_expected, c.checks_ran,",
            "       CAST(c.checks_ran AS FLOAT) / NULLIFZERO(c.checks_expected) AS coverage,",
            "       c.passed_count, c.failed_count, c.error_count, c.critical_failure_count, c.error_failure_count,",
            f"       CASE WHEN c.stale = 1 THEN 'Evidence is stale since ' || CAST(COALESCE(c.evidence_expires_dts, c.completed_dts + {window}) "
            "AS VARCHAR(40)) || '.' ELSE c.open_gaps END AS open_gaps,",
            "       CASE WHEN c.stale = 1 THEN 'Re-run the validator; disclose unknown confidence.'",
            "            WHEN c.designated IS NULL THEN 'No designated producer: cautious per-area fallback. ' || "
            "COALESCE(c.recommended_action, 'Designate one producer.')",
            "            ELSE c.recommended_action END AS recommended_action,",
            "       c.completed_dts, c.derived",
            "FROM (", "    SELECT l.*", "    FROM (",
            "        SELECT e.*, p.producer_id AS designated,",
            f"               CASE WHEN COALESCE(e.evidence_expires_dts, e.completed_dts + {window}) < CURRENT_TIMESTAMP(6) THEN 1 ELSE 0 END AS stale",
            f"        FROM {evidence} e",
            f"        JOIN {product} p ON p.product_code = e.product_code AND (p.producer_id IS NULL OR p.producer_id = e.producer_id)",
            "        QUALIFY ROW_NUMBER() OVER (PARTITION BY e.product_code, e.producer_id, e.scope_kind, e.scope_id",
            "                                   ORDER BY e.completed_dts DESC, e.run_id DESC) = 1",
            "    ) l",
            "    QUALIFY ROW_NUMBER() OVER (PARTITION BY l.product_code, l.scope_kind, l.scope_id",
            "                               ORDER BY CASE WHEN l.stale = 1 THEN 0",
            "                                             ELSE CASE l.confidence WHEN 'unknown' THEN 0 WHEN 'weak' THEN 1 "
            "WHEN 'partial' THEN 2 ELSE 3 END END,",
            "                                        l.completed_dts DESC, l.run_id DESC, l.producer_id) = 1",
            ") c", "UNION ALL",
            "SELECT p.product_code, p.producer_id, CAST(NULL AS VARCHAR(400)), 'PRODUCT', p.product_code, 'no-evidence', 'unknown',",
            "       0, 0, CAST(NULL AS FLOAT), 0, 0, 0, 0, 0, 'No published area evidence.', 'Run the validator before reporting confidence.',",
            "       CAST(NULL AS TIMESTAMP(6) WITH TIME ZONE), 0",
            f"FROM {product} p",
            f"WHERE NOT EXISTS (SELECT 1 FROM {evidence} e WHERE e.product_code = p.product_code",
            "                  AND (p.producer_id IS NULL OR e.producer_id = p.producer_id));",
            f"COMMENT ON VIEW {v} IS {self.comment(self.TRUST_NOTE)};"]
        lines += [f"COMMENT ON COLUMN {v}.{ident(name)} IS {self.comment(meaning)};" for name, meaning in self.TRUST_COLUMNS]
        return "\n".join(lines)

